"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { useSession } from "@/components/shared/SessionContext";
import { UrgencyBanner } from "@/components/results/UrgencyBanner";
import { ConditionCard } from "@/components/results/ConditionCard";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import type { UrgencyLevel, ConditionScore } from "@/lib/inference/types";
import { FileText, AlertTriangle } from "lucide-react";

interface AnalysisResult {
  urgencyLevel: UrgencyLevel;
  urgencyReason: string;
  redFlags: string[];
  conditionGroups: ConditionScore[];
  cached?: boolean;
}

export default function ResultsPage() {
  const router = useRouter();
  const { sessionId } = useSession();
  const [result, setResult] = useState<AnalysisResult | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!sessionId) { router.push("/consent"); return; }

    fetch("/api/analyze", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ sessionId }),
    })
      .then(async (res) => {
        if (!res.ok) throw new Error("Failed to load results");
        return res.json();
      })
      .then(setResult)
      .catch(() => setError("Could not load results. Please try again."))
      .finally(() => setLoading(false));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sessionId]);

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center">
        <div className="w-8 h-8 rounded-full border-4 border-blue-200 border-t-blue-600 animate-spin" />
      </div>
    );
  }

  if (error || !result) {
    return (
      <div className="min-h-screen flex items-center justify-center px-4">
        <div className="text-center space-y-4">
          <AlertTriangle className="h-10 w-10 text-amber-500 mx-auto" />
          <p className="text-muted-foreground">{error ?? "No results found."}</p>
          <Button onClick={() => router.push("/")}>Start over</Button>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-gray-50">
      <div className="max-w-lg mx-auto px-4 py-8 space-y-5">
        <div>
          <p className="text-xs text-muted-foreground uppercase tracking-wide mb-1">Step 7 of 7</p>
          <h1 className="text-2xl font-bold">Your triage results</h1>
          <p className="text-sm text-muted-foreground mt-1">
            Results are based on visual pattern analysis and your symptom answers. They are not a diagnosis.
          </p>
        </div>

        {/* Urgency — always first */}
        <UrgencyBanner
          level={result.urgencyLevel}
          reason={result.urgencyReason}
          redFlags={result.redFlags}
        />

        {/* Condition groups */}
        {result.conditionGroups.length > 0 ? (
          <div className="space-y-4">
            <h2 className="font-semibold text-sm uppercase tracking-wide text-muted-foreground">
              Pattern matches ({result.conditionGroups.length})
            </h2>
            {result.conditionGroups.map((score) => (
              <ConditionCard key={score.groupId} score={score} />
            ))}
          </div>
        ) : (
          <Card>
            <CardContent className="pt-6 pb-6 text-center text-muted-foreground text-sm">
              No specific pattern matches identified. If you have ongoing concerns, see your GP.
            </CardContent>
          </Card>
        )}

        {/* Demo mode notice */}
        <Card className="border-dashed border-gray-300 bg-gray-50">
          <CardContent className="pt-4 pb-4">
            <p className="text-xs text-muted-foreground text-center">
              <strong>Demo mode:</strong> Results are generated by a mock engine. Real computer vision models will be integrated in Phase 2.
            </p>
          </CardContent>
        </Card>

        {/* Generate summary CTA */}
        <Button
          className="w-full gap-2"
          size="lg"
          onClick={() => router.push("/summary")}
        >
          <FileText className="h-4 w-4" />
          Generate doctor summary
        </Button>

        <p className="text-xs text-muted-foreground text-center">
          The summary is a structured note you can take to your GP or specialist.
        </p>
      </div>
    </div>
  );
}
